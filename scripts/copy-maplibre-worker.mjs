// Copy MapLibre's worker (and the shared module it imports) next to the site so
// the map can load it from a plain URL under any bundler. Runs before dev and
// build (see package.json); the copies are git-ignored.
//
// The real files go in a folder named for the MapLibre version, which
// next.config.ts serves as immutable (a year in the browser cache). The URL the
// map asks for, /vendor/maplibre-gl-worker.mjs, is a one-line module that
// imports the versioned worker, so an upgrade changes what it points at and no
// visitor keeps a worker that doesn't match the map code.
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
const require = createRequire(import.meta.url);
const pkg = require.resolve("maplibre-gl/package.json");
const { version } = require(pkg);
const dist = path.join(path.dirname(pkg), "dist");
const outDir = path.join(process.cwd(), "public", "vendor");
const versionDir = path.join(outDir, "maplibre-gl", version);
// Older copies, including the unversioned shared module from before, aren't served any more.
rmSync(path.join(outDir, "maplibre-gl"), { recursive: true, force: true });
rmSync(path.join(outDir, "maplibre-gl-shared.mjs"), { force: true });
mkdirSync(versionDir, { recursive: true });
for (const f of ["maplibre-gl-worker.mjs", "maplibre-gl-shared.mjs"]) copyFileSync(path.join(dist, f), path.join(versionDir, f));
writeFileSync(
  path.join(outDir, "maplibre-gl-worker.mjs"),
  `// MapLibre GL ${version}. Generated by scripts/copy-maplibre-worker.mjs.\nimport "./maplibre-gl/${version}/maplibre-gl-worker.mjs";\n`,
);
console.log(`copied maplibre worker ${version} → public/vendor/maplibre-gl/${version}/`);
